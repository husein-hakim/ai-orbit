CSV_COLUMNS = [
    "mcp_name",
    "type",
    "category",
    "subcategory",
    "company_creator",
    "official_website",
    "github_url",
    "logo_url",
    "description",
    "primary_use_case",
    "key_capabilities",
    "programming_language",
    "open_source",
    "license",
    "pricing",
    "supported_platforms",
    "github_stars",
    "active",
    "is_official",
    "discovery_source",
    "quality_score",
    "last_verified",
]


def write_csv(data: list[dict], output_path: str) -> None:
    """Write curated data to a CSV file."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=CSV_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for row in data:
            writer.writerow(row)
    print(f"✅ Wrote {len(data)} records to {output_path}")


def write_json(data: list[dict], output_path: str) -> None:
    """Write curated data to a JSON file."""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False, default=str)
    print(f"✅ Wrote {len(data)} records to {output_path}")


def print_summary(data: list[dict]) -> None:
    """Print a summary of the extracted data."""
    print("\n" + "=" * 60)
    print("AIOrbit MCP Dataset — Extraction Summary")
    print("=" * 60)
    print(f"  Total records:    {len(data)}")

    categories = {}
    for r in data:
        cat = r.get("category", "Unknown")
        categories[cat] = categories.get(cat, 0) + 1
    print(f"  Categories:       {len(categories)}")

    official = sum(1 for r in data if r.get("is_official"))
    print(f"  Official servers: {official}")
    print(f"  Community:        {len(data) - official}")

    types = {}
    for r in data:
        t = r.get("type", "Unknown")
        types[t] = types.get(t, 0) + 1
    for t, count in sorted(types.items()):
        print(f"  Type {t}: {count}")

    scores = [r.get("quality_score", 0) for r in data]
    if scores:
        print(f"  Avg quality:      {sum(scores) / len(scores):.1f}")
        print(f"  Min quality:      {min(scores)}")
        print(f"  Max quality:      {max(scores)}")

    print("\n  Records by category:")
    for cat, count in sorted(categories.items(), key=lambda x: -x[1]):
        print(f"    {cat}: {count}")

    print("=" * 60)


