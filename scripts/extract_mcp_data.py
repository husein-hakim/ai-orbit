def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    final_dir = os.path.join(base_dir, "data", "final")

    # Remove duplicates by name
    seen = set()
    unique = []
    for r in CURATED_MCP_DATA:
        name = r["mcp_name"].lower().strip()
        if name not in seen:
            seen.add(name)
            unique.append(r)
        else:
            print(f"⚠️  Duplicate removed: {r['mcp_name']}")

    print_summary(unique)

    # Write outputs
    csv_path = os.path.join(final_dir, "mcp_dataset.csv")
    json_path = os.path.join(final_dir, "mcp_dataset.json")
    write_csv(unique, csv_path)
    write_json(unique, json_path)

    print(f"\n🎉 Dataset generation complete!")
    print(f"   CSV: {csv_path}")
    print(f"   JSON: {json_path}")


if __name__ == "__main__":
    main()
